from collections.abc import Iterator

from score.itf.core import provides


class Store:
    def __init__(self):
        self.data = {}

    def get(self, key):
        return self.data.get(key)

    def put(self, key, value):
        self.data[key] = value


@provides("kv.store", name="fake_kv.memory_store")
def make_store(config) -> Iterator[Store]:
    store = Store()
    yield store
    store.data.clear()
